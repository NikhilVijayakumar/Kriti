# ---------------------------------------------------------------------------
# Legacy template migration
# ---------------------------------------------------------------------------

def migrate_legacy_templates():
    """Rename summary -> whole-paper-summary; delete deterministic & semantic shared."""
    md_dir = OUTPUT / "markdown"
    html_dir = OUTPUT / "html"

    # Rename summary -> whole-paper-summary
    for old_name, new_name in [
        ("summary.md", "whole-paper-summary.md"),
        ("summary.html", "whole-paper-summary.html"),
    ]:
        old = md_dir / old_name if old_name.endswith(".md") else html_dir / old_name
        new = md_dir / new_name if new_name.endswith(".md") else html_dir / new_name
        if old.exists():
            old.rename(new)
            print(f"  Renamed {old.name} -> {new.name}")

    # Delete obsolete shared templates
    for fname in ["deterministic.md", "semantic.md"]:
        fpath = md_dir / fname
        if fpath.exists():
            fpath.unlink()
            print(f"  Deleted {fpath}")

    for fname in ["deterministic.html", "semantic.html"]:
        fpath = html_dir / fname
        if fpath.exists():
            fpath.unlink()
            print(f"  Deleted {fpath}")


# ---------------------------------------------------------------------------
# Whole-paper-summary patch — append domain aggregation scores table
# ---------------------------------------------------------------------------

def patch_whole_paper_summary():
    """Add 12-domain aggregate scores table to the renamed whole-paper-summary files."""
    md_path = OUTPUT / "markdown" / "whole-paper-summary.md"
    html_path = OUTPUT / "html" / "whole-paper-summary.html"

    if md_path.exists():
        content = md_path.read_text(encoding="utf-8")
        agg_block = (
            "\n## Domain Aggregation Scores\n"
            "\n"
            "| Domain | Final Score | Score Band |\n"
            "|--------|-------------|------------|\n"
            "{{#domain_aggregates}}\n"
            "| {{ domain_key }} | {{ final_score }} | {{ score_band }} |\n"
            "{{/domain_aggregates}}\n"
        )
        # Insert before the final "*Report generated" line
        marker = "*Report generated by base_academic audit pipeline.*"
        if marker in content and "Domain Aggregation Scores" not in content:
            content = content.replace(marker, agg_block.strip() + "\n\n" + marker)
            md_path.write_text(content, encoding="utf-8")
            print("  Patched whole-paper-summary.md with domain aggregation table")

    if html_path.exists():
        content = html_path.read_text(encoding="utf-8")
        agg_block = (
            "\n    <h2>Domain Aggregation Scores</h2>\n"
            "    <table>\n"
            "        <thead>\n"
            "            <tr><th>Domain</th><th>Final Score</th><th>Score Band</th></tr>\n"
            "        </thead>\n"
            "        <tbody>\n"
            "            {{#domain_aggregates}}\n"
            "            <tr>\n"
            "                <td><strong>{{ domain_key }}</strong></td>\n"
            "                <td>{{ final_score }}</td>\n"
            "                <td>{{ score_band }}</td>\n"
            "            </tr>\n"
            "            {{/domain_aggregates}}\n"
            "        </tbody>\n"
            "    </table>\n"
        )
        marker = '<p class="meta">Report generated by base_academic audit pipeline.</p>'
        if marker in content and "Domain Aggregation Scores" not in content:
            content = content.replace(marker, agg_block.strip() + "\n\n    " + marker)
            html_path.write_text(content, encoding="utf-8")
            print("  Patched whole-paper-summary.html with domain aggregation table")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    count = 0

    print(f"Output base: {OUTPUT}\n")

    # --- Phase 1: generate per-domain templates ---
    print("Generating per-domain report templates...")
    for domain in DOMAINS:
        dn = DISPLAY_NAMES[domain]
        md_dir = OUTPUT / "markdown" / "domain" / domain
        html_dir = OUTPUT / "html" / "domain" / domain
        md_dir.mkdir(parents=True, exist_ok=True)
        html_dir.mkdir(parents=True, exist_ok=True)

        for kind, md_builder in MARKDOWN_BUILDERS.items():
            md_path = md_dir / f"{kind}.md"
            md_path.write_text(md_builder(dn), encoding="utf-8")
            count += 1
            print(f"  {md_path.relative_to(OUTPUT)}")

        for kind, html_builder in HTML_BUILDERS.items():
            html_path = html_dir / f"{kind}.html"
            html_path.write_text(html_builder(dn), encoding="utf-8")
            count += 1
            print(f"  {html_path.relative_to(OUTPUT)}")

    # --- Phase 2: legacy migration ---
    print("\nMigrating legacy shared templates...")
    migrate_legacy_templates()

    # --- Phase 3: patch whole-paper-summary ---
    print("\nPatching whole-paper-summary with domain aggregation table...")
    patch_whole_paper_summary()

    print(f"\nDone. Total files written: {count}")


if __name__ == "__main__":
    main()
