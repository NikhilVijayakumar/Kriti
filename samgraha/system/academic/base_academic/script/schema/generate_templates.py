def html_boilerplate(title, body):
    return (
        "<!DOCTYPE html>\n"
        '<html lang="en">\n'
        "<head>\n"
        '    <meta charset="UTF-8">\n'
        '    <meta name="viewport" content="width=device-width, initial-scale=1.0">\n'
        f"    <title>{title}</title>\n"
        "    <style>\n"
        + "\n".join(f"        {line}" for line in CSS.split("\n"))
        + "\n    </style>\n"
        "</head>\n"
        "<body>\n"
        + "\n".join(f"    {line}" for line in body.split("\n"))
        + "\n</body>\n"
        "</html>\n"
    )


